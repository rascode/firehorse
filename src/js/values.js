// Firehorse data display contract: one way to show a value, everywhere.
//
//   import { resolveValue } from "@rascode/firehorse/values";
//   resolveValue({ key: "state", semanticType: "status" }, "cell");
//   // → { shape: "option", row: "option.status", variant: "dot", id: "VAL-1.1", group: "VAL-1", ... }
//
// A surface (datatable, table, record table, metric, card, sidecar, form) never decides how a value looks:
// it hands the field to resolveValue() with its context, and draws the variant it gets back.
// The field decides (its semantic type, option set or entity kind); the rule grid in schema/display-rules.json
// decides what to draw in each context; a field may name a variant, a surface never can (rule 5).
// Rules and semantic types come from value-rules.js (generated by scripts/value-rules.mjs).
// Agent doc: agent/components/values.md.
import { rules, semanticTypes } from "./value-rules.js";

export { rules, semanticTypes };

/** The thirteen shapes, in display-rules.json order. */
export const SHAPES = Object.freeze(Object.keys(rules.shapes));
/** The five contexts: cell, record, card, metric, form. */
export const CONTEXTS = Object.freeze(Object.keys(rules.contexts));
/** Empty is a muted em dash, never a blank cell or null (rule 7). */
export const EMPTY = Object.freeze({ ...rules.empty });

const toneByWord = new Map();
for (const [tone, words] of Object.entries(rules.toneMap)) for (const w of words) toneByWord.set(w, tone);

/** The default tone of a status word (the Status chip's map): done lime, moving sky, waiting amber, failed rose, else neutral. */
export function defaultTone(value) {
  return toneByWord.get(String(value ?? "").trim().toLowerCase()) ?? "neutral";
}

/** Computed and system types are read-only: they resolve to their record variant in a form. */
export function isReadOnly(semanticType) {
  if (!semanticType) return false;
  const { prefixes = [], keys = [] } = rules.readOnly ?? {};
  return keys.includes(semanticType) || prefixes.some((p) => semanticType.startsWith(p));
}

/** Is this a value with nothing to show (null, undefined, "", or an empty list)? */
export function isEmpty(value) {
  return value == null || value === "" || (Array.isArray(value) && value.length === 0);
}

/**
 * What a field is, before any context: its shape, kind, unit, semantic type and whether it holds several values.
 * Precedence: the field's own shape/kind, then its datatable type alias, then its semantic type, then text.
 * field: { key, semanticType?, type? (one of the datatable's 22 types), shape?, kind?, entity?, multiple?, unit?, readOnly? }
 */
export function describeField(field = {}) {
  const alias = field.type ? rules.aliases[field.type] : undefined;
  const semanticKey = field.semanticType ?? alias?.semanticType ?? null;
  const semantic = semanticKey ? semanticTypes[semanticKey] : undefined;
  const warnings = [];
  if (field.type && !alias) warnings.push(`unknown datatable type "${field.type}"`);
  if (semanticKey && !semantic) warnings.push(`unknown semantic type "${semanticKey}"`);
  let shape = field.shape ?? alias?.shape ?? semantic?.shape ?? "text";
  let kind = field.kind ?? field.entity ?? alias?.kind ?? semantic?.kind ?? null;
  if (!rules.shapes[shape]) {
    warnings.push(`unknown shape "${shape}", drawn as text`);
    shape = "text";
    kind = null;
  }
  let multiple = field.multiple ?? alias?.multiple ?? shape === "options";
  // Several values from a set are the options shape, whatever the field called itself.
  if (shape === "option" && multiple) shape = "options";
  if (shape === "options") multiple = true;
  return {
    shape,
    kind,
    unit: field.unit ?? semantic?.unit ?? null,
    semanticType: semantic ? semanticKey : null,
    alias: alias ? field.type : null,
    multiple: Boolean(multiple),
    readOnly: Boolean(field.readOnly ?? isReadOnly(semanticKey)),
    display: { ...(alias?.display ?? {}), ...(field.display ?? {}) },
    warnings,
  };
}

/**
 * The option set a field draws from, with every option's tone filled in (its own, else the default tone map).
 * Sources, first found: field.optionSet as an object; field.optionSet as a key in opts.optionSets;
 * field.options (strings or { value, label, tone }); the semantic type's own options (key semantic.<type>).
 * Returns { key, kind, options: [{ value, label, tone, icon?, description?, live? }] } or null.
 */
export function optionSetFor(field = {}, opts = {}) {
  const d = describeField(field);
  let set = null;
  if (field.optionSet && typeof field.optionSet === "object") set = field.optionSet;
  else if (typeof field.optionSet === "string" && opts.optionSets?.[field.optionSet]) set = { key: field.optionSet, ...opts.optionSets[field.optionSet] };
  else if (Array.isArray(field.options)) set = { key: field.optionSet ?? (field.key ? `field.${field.key}` : null), options: field.options };
  else if (d.semanticType && semanticTypes[d.semanticType].options) set = { key: `semantic.${d.semanticType}`, options: semanticTypes[d.semanticType].options };
  if (!set) return null;
  const status = (set.kind ?? (d.kind === "status" ? "status" : "choice")) === "status";
  return {
    key: set.key ?? null,
    kind: status ? "status" : "choice",
    ...(set.label ? { label: set.label } : {}),
    ...(set.ordinal ? { ordinal: true } : {}),
    options: set.options.map((o) => {
      const opt = typeof o === "object" && o !== null ? o : { value: o };
      return { ...opt, label: opt.label ?? String(opt.value), tone: opt.tone ?? defaultTone(opt.value) };
    }),
  };
}

/** The tone of one value in a set: the option's tone, else the default tone map. */
export function toneOf(set, value) {
  const hit = set?.options?.find((o) => String(o.value) === String(value));
  return hit?.tone ?? defaultTone(value);
}

function matches(row, d, count) {
  if (row.shape !== d.shape) return false;
  const m = row.match;
  if (!m) return true;
  if (m.kind && !m.kind.includes(d.kind)) return false;
  if (m.multiple !== undefined && m.multiple !== d.multiple) return false;
  if (m.count) {
    if (count == null) return false;
    const [lo, hi] = m.count;
    if ((lo != null && count < lo) || (hi != null && count > hi)) return false;
  }
  return true;
}

/** The grid row a described field falls on (first match in display-rules.json order). */
export function gridRow(d, count = null) {
  return rules.grid.find((row) => matches(row, d, count)) ?? rules.grid.find((row) => row.shape === "text" && !row.match);
}

/**
 * How to draw a field's value here.
 *   field    the field (see describeField); `display: { cell: "chip" }` names a variant for a context (rule 5)
 *   context  "cell" | "record" | "card" | "metric" | "form"
 *   mode     "read" | "edit" (default: edit in a form, read elsewhere)
 *   opts     { optionSets } a registry of option sets by key
 * Returns { shape, kind, row, context, mode, variant, id (the variant's Index ID, VAL-1.1), label, group, parts, editable, control, readOnly, align,
 *   figures, mono, max, unit, currency, optionSet, empty, source, warnings }.
 * variant is null when the grid leaves the field out of that context (metric for prose, say): the surface skips it.
 * In edit mode outside a form, the read variant stays and gains its control (rule 6): editable + control.
 */
export function resolveValue(field = {}, context = "cell", mode, opts = {}) {
  if (!rules.contexts[context]) throw new TypeError(`unknown context "${context}" (one of ${CONTEXTS.join(", ")})`);
  mode ??= context === "form" ? "edit" : "read";
  if (!rules.modes.includes(mode)) throw new TypeError(`unknown mode "${mode}" (read or edit)`);
  const d = describeField(field);
  const warnings = [...d.warnings];
  const optionSet = d.shape === "option" || d.shape === "options" ? optionSetFor(field, opts) : null;
  const row = gridRow(d, optionSet ? optionSet.options.length : null);
  const family = rules.variants[d.shape];
  let variant = row[context] ?? null;
  let source = "grid";
  // A ratio with a target is a meter in the metric context (the grid's note).
  if (d.shape === "ratio" && context === "metric" && field.target != null) variant = "meter";
  const wanted = d.display[context];
  if (wanted !== undefined) {
    if (wanted === null || family.variants[wanted]) {
      variant = wanted;
      source = "field";
    } else warnings.push(`variant "${wanted}" is not a ${d.shape} variant; the grid's "${variant}" is used`);
  }
  let editable = false;
  let control = null;
  let readOnly = d.readOnly;
  if (context === "form") {
    if (mode === "read" || readOnly || !variant || !family.variants[variant]?.editable) {
      // Nothing to edit: the form shows the value as the record row does.
      readOnly = true;
      variant = row.record;
      source = "grid";
    } else editable = true;
  } else if (mode === "edit" && !readOnly && row.form) {
    editable = true;
    control = row.form;
  }
  const meta = variant ? family.variants[variant] : null;
  if (d.shape === "money" && !field.currency) warnings.push("money without a currency (rule 4): send field.currency");
  const numeric = d.shape === "number" || d.shape === "money" || d.shape === "ratio";
  return {
    shape: d.shape,
    kind: d.kind,
    semanticType: d.semanticType,
    row: row.row,
    context,
    mode,
    variant,
    id: meta?.id ?? null,
    label: meta?.label ?? null,
    group: family.group,
    parts: meta?.parts ?? [],
    editable,
    control,
    readOnly,
    align: row.align?.[context] ?? "start",
    figures: numeric && (context === "cell" || context === "record") ? "tabular" : null,
    mono: Boolean(row.mono),
    max: row.max?.[context] ?? null,
    multiple: d.multiple,
    unit: d.unit,
    currency: d.shape === "money" ? (field.currency ?? null) : null,
    optionSet,
    empty: EMPTY,
    source,
    warnings,
  };
}
