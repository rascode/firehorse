// Generates src/tokens/adaptive.css: text and tone tokens computed from the
// background they sit on, using CSS relative color math. No JavaScript at
// runtime; this script only writes the CSS. Re-run after changing a palette.
//
//   node scripts/gen-adaptive.mjs
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// OKLCH of each family on dark backgrounds (400-level) and light backgrounds (700-level).
// [L, C, H] — L is the brightest/darkest the tone is allowed to sit at by default.
const palette = {
  sky: [[0.754, 0.139, 232.7], [0.5, 0.119, 242.7]],
  lime: [[0.849, 0.207, 128.8], [0.532, 0.141, 131.6]],
  orange: [[0.758, 0.159, 55.9], [0.553, 0.174, 38.4]],
  teal: [[0.785, 0.133, 181.9], [0.511, 0.086, 186.4]],
  fuchsia: [[0.748, 0.207, 322.2], [0.518, 0.226, 323.9]],
  violet: [[0.709, 0.159, 293.5], [0.491, 0.241, 292.6]],
  rose: [[0.719, 0.169, 13.4], [0.514, 0.198, 16.9]],
  amber: [[0.837, 0.164, 84.4], [0.555, 0.146, 49.0]],
  ember: [[0.628, 0.212, 35.1], [0.509, 0.174, 36.1]],
  success: [[0.849, 0.207, 128.8], [0.527, 0.137, 150.1]],
  danger: [[0.626, 0.193, 23.0], [0.541, 0.192, 25.1]],
  warning: [[0.837, 0.164, 84.4], [0.555, 0.146, 49.0]],
  live: [[0.723, 0.192, 149.6], [0.527, 0.137, 150.1]],
};

// D is 1 on a dark background and 0 on a light one: a step at L = 0.62,
// written as a clamp so it needs no conditionals.
const D = "clamp(0, (0.62 - l) * 999, 1)";
const mix = (dark, light) => `calc(${D} * ${dark} + (1 - ${D}) * ${light})`;
// Neutral text: offset from the background's own lightness, clamped to a range.
const neutral = (up, down, hi, lo, floor, chroma = 0) => `oklch(from var(--fh-color-bg) ${mix(`clamp(${floor}, l + ${up}, ${hi})`, `max(l - ${down}, ${lo})`)} ${chroma} h)`;
const tone = (n) => {
  const v = (s, i) => `var(--fh-${n}-${s}${i})`;
  return `oklch(from var(--fh-color-bg) ${mix(`max(l + 0.55, ${v("d", "l")})`, `min(l - 0.47, ${v("l", "l")})`)} ${mix(v("d", "c"), v("l", "c"))} ${mix(v("d", "h"), v("l", "h"))})`;
};

let nums = "";
for (const [n, [d, l]] of Object.entries(palette)) {
  nums += `    --fh-${n}-dl: ${d[0]}; --fh-${n}-dc: ${d[1]}; --fh-${n}-dh: ${d[2]};\n`;
  nums += `    --fh-${n}-ll: ${l[0]}; --fh-${n}-lc: ${l[1]}; --fh-${n}-lh: ${l[2]};\n`;
}

const tones = ["sky", "lime", "orange", "teal", "fuchsia", "violet", "rose", "amber"];
const css = `/*
 * Firehorse — adaptive color
 * ---------------------------------------------------------------
 * GENERATED by scripts/gen-adaptive.mjs. Edit the script, not this file.
 *
 * Text and tone tokens are computed from the background they sit on
 * (--fh-color-bg) with CSS relative color math. Lightness is offset from
 * the background's own L in OKLCH and clamped, so any canvas you choose,
 * light, dark or branded, gets readable text and tones without a second
 * palette and without JavaScript.
 *
 *   D = clamp(0, (0.62 - L_bg) * 999, 1)     1 on dark, 0 on light
 *   text   = 0.955 on dark, 0.20 on light
 *   muted  = L_bg + 0.48 on dark (at least 0.66), L_bg - 0.51 on light
 *   tone   = max(L_bg + 0.55, L_400) on dark, min(L_bg - 0.47, L_700) on light
 *   on-tone= white or ink, chosen from the tone's own lightness
 *
 * A theme ([data-fh-theme]) re-runs the same math against its own canvas.
 *
 * Paint any surface and let everything inside adapt:
 *   <section data-fh-surface style="--fh-color-bg: #f3ede2">…</section>
 *   <div data-fh-surface="raised">…</div>
 *
 * Browsers without relative color keep the static palette in semantic.css.
 */

@layer fh.tokens {
  :root {
    --fh-color-bg: var(--fh-color-canvas);
${nums}  }

  [data-fh-surface="raised"] { --fh-color-bg: var(--fh-color-surface-raised); }
  [data-fh-surface="sunken"] { --fh-color-bg: var(--fh-color-surface-sunken); }
  [data-fh-surface="chrome"] { --fh-color-bg: var(--fh-color-surface-chrome); }
  [data-fh-surface="inverse"] { --fh-color-bg: light-dark(var(--fh-gray-950), var(--fh-gray-50)); }
  [data-fh-surface="tone"] { --fh-color-bg: color-mix(in oklab, var(--fh-tone) 16%, var(--fh-color-canvas)); }
  [data-fh-surface="tone-solid"] { --fh-color-bg: var(--fh-tone); }

  @supports (color: oklch(from red l c h)) {
    :root,
    [data-fh-theme],
    [data-fh-surface] {
      --fh-color-text: oklch(from var(--fh-color-bg) clamp(0.2, (0.62 - l) * 999, 0.955) 0 h);
      --fh-color-text-strong: oklch(from var(--fh-color-bg) clamp(0, (0.62 - l) * 999, 1) 0 h);
      --fh-color-text-muted: ${neutral(0.48, 0.51, 0.86, 0.3, 0.66)};
      --fh-color-text-subtle: ${neutral(0.433, 0.457, 0.8, 0.34, 0.6)};
      --fh-color-text-placeholder: oklch(from var(--fh-color-field) ${mix("min(l + 0.37, 0.82)", "max(l - 0.44, 0.34)")} 0 h);
      --fh-color-text-inverse: oklch(from var(--fh-color-bg) l 0 h);
${tones.map((t) => `      --fh-tone-${t}: ${tone(t)};`).join("\n")}
      --fh-color-accent-text: ${tone("ember")};
      --fh-color-success: ${tone("success")};
      --fh-color-danger: ${tone("danger")};
      --fh-color-warning: ${tone("warning")};
      --fh-color-live: ${tone("live")};
    }

    /* Text on a tone fill: ink or white, from the fill's own lightness. */
    :root,
    [data-fh-theme],
    [data-tone],
    [data-fh-surface] {
      --fh-color-on-tone: oklch(from var(--fh-tone) clamp(0.2, (0.62 - l) * 999, 1) 0 h);
    }
  }
}
`;
writeFileSync(join(root, "src/tokens/adaptive.css"), css);
console.log("src/tokens/adaptive.css written");
