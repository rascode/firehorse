// Builds src/icons/icons.css from Lucide (ISC) SVGs: one mask-based class per
// icon, so icons take currentColor and size with the text they sit in.
//   node scripts/gen-icons.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const ICONS = {
  interface: ["search", "plus", "minus", "x", "check", "chevron-down", "chevron-up", "chevron-left", "chevron-right", "chevrons-up-down", "arrow-right", "arrow-left", "arrow-up-right", "arrow-up-down", "menu", "ellipsis", "ellipsis-vertical", "filter", "sliders-horizontal", "settings", "eye", "eye-off", "lock", "lock-open", "copy", "link", "external-link", "share-2", "download", "upload", "trash-2", "pencil", "square-pen", "refresh-cw", "loader-circle", "maximize-2", "minimize-2", "grip-vertical", "panel-right", "panel-left", "command", "log-in", "log-out", "house", "info", "circle-help", "circle-check", "circle-x", "circle-alert", "triangle-alert", "bell", "bookmark", "star", "heart", "flag", "pin"],
  layout: ["layout-grid", "list", "table-2", "kanban", "columns-3", "rows-3", "gallery-vertical-end", "layers", "panels-top-left", "square", "rectangle-horizontal"],
  data: ["database", "server", "hash", "type", "calendar", "calendar-days", "clock", "at-sign", "phone", "mail", "globe", "map-pin", "paperclip", "image", "file", "file-text", "folder", "tag", "percent", "dollar-sign", "chart-bar", "chart-line", "chart-pie", "trending-up", "trending-down", "activity", "sigma", "toggle-right", "list-checks", "circle-dot", "link-2", "barcode", "qr-code"],
  people: ["user", "users", "user-plus", "user-round-check", "building-2", "briefcase", "badge-check", "message-square", "message-circle", "send", "mic", "video", "contact"],
  commerce: ["shopping-cart", "shopping-bag", "credit-card", "wallet", "receipt", "truck", "package", "gift", "store", "badge-percent", "ticket", "box", "ruler", "scan-barcode", "shield-check", "rotate-ccw"],
  media: ["play", "pause", "skip-back", "skip-forward", "rotate-cw", "repeat", "repeat-1", "shuffle", "volume", "volume-1", "volume-2", "volume-x", "music", "audio-lines", "audio-waveform", "headphones", "mic-vocal", "radio", "disc-3", "captions", "sliders-vertical", "gauge", "list-music", "podcast"],
  ai: ["sparkles", "wand-sparkles", "bot", "brain", "cpu", "zap", "workflow", "git-branch", "code", "terminal", "rocket", "flame", "palette", "accessibility", "sun", "moon", "monitor", "smartphone", "keyboard", "mouse-pointer-click", "target", "award", "leaf", "coffee"],
  social: ["youtube", "linkedin", "facebook", "twitter", "instagram", "github"],
};
const all = Object.values(ICONS).flat();
let css = `/*
 * Firehorse — icons
 * ---------------------------------------------------------------
 * GENERATED by scripts/gen-icons.mjs from Lucide (ISC license,
 * https://lucide.dev). ${all.length} icons as CSS masks: they take the text
 * color and scale with font-size, so one class works in a chip, a
 * heading, a button or a table header.
 *
 *   <i class="fh-icon fh-icon--search" aria-hidden="true"></i>
 *
 * Optional: import "@rascode/firehorse/icons.css" alongside the core.
 * Social marks are generic glyphs; follow each platform's brand rules.
 */
@layer fh.components {
  .fh-icon {
    display: inline-block;
    flex: none;
    inline-size: var(--fh-icon-size, 1em);
    block-size: var(--fh-icon-size, 1em);
    vertical-align: -0.125em;
    background-color: currentColor;
    mask: var(--fh-icon) center / contain no-repeat;
  }
  .fh-icon--sm { --fh-icon-size: 0.85em; }
  .fh-icon--lg { --fh-icon-size: 1.25em; }
  .fh-icon--tone { color: var(--fh-tone); }

  /* Icon tile: a tone-tinted square that holds an icon. */
  .fh-icon-tile {
    display: inline-grid;
    place-items: center;
    flex: none;
    inline-size: var(--fh-icon-tile, 2.25rem);
    aspect-ratio: 1;
    border-radius: var(--fh-radius-md);
    background-color: color-mix(in oklab, var(--fh-tone) 14%, transparent);
    color: var(--fh-tone);
    font-size: calc(var(--fh-icon-tile, 2.25rem) * 0.46);
  }
  .fh-icon-tile--solid { background-color: var(--fh-tone); color: var(--fh-color-on-tone); }
`;
for (const n of all) {
  const svg = readFileSync(join(root, "node_modules/lucide-static/icons", `${n}.svg`), "utf8")
    .replace(/<!--.*?-->/s, "").replace(/\s*class="[^"]*"/, "").replace(/\s+/g, " ").replace(/> </g, "><").trim()
    .replace(/stroke="currentColor"/, 'stroke="black"');
  const uri = "data:image/svg+xml," + svg.replace(/"/g, "'").replace(/[<>#%{}]/g, (c) => encodeURIComponent(c));
  css += `  .fh-icon--${n} { --fh-icon: url("${uri}"); }\n`;
}
css += "}\n";
mkdirSync(join(root, "src/icons"), { recursive: true });
writeFileSync(join(root, "src/icons/icons.css"), css);
writeFileSync(join(root, "src/icons/icons.json"), JSON.stringify(ICONS, null, 2) + "\n");
console.log(`src/icons/icons.css: ${all.length} icons`);
