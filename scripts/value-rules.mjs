// Writes src/js/value-rules.js from schema/display-rules.json and schema/semantic-types.json, so resolveValue()
// (src/js/values.js) reads the same contract in the browser and in Node without a JSON import, and fills the
// generated sections of agent/components/values.md (rules, grid, aliases, types) so the doc cannot drift.
//   node scripts/value-rules.mjs          write
//   node scripts/value-rules.mjs --check  exit 1 when the file is not current (npm test)
// Data display contract W1 (platform relay/2026-11-14-data-display-contract-plan.md).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const rules = JSON.parse(readFileSync(join(root, "schema/display-rules.json"), "utf8"));
const types = JSON.parse(readFileSync(join(root, "schema/semantic-types.json"), "utf8")).types;
const { $comment, ...contract } = rules;
const semantic = {};
for (const t of types) {
  if (!t.display?.shape) throw new Error(`semantic type ${t.key} has no display shape (migration 434)`);
  semantic[t.key] = { label: t.label, shape: t.display.shape, kind: t.display.kind ?? null, unit: t.display.unit ?? null, options: Array.isArray(t.options?.options) ? t.options.options : null };
}
const body = `// Generated by scripts/value-rules.mjs from schema/display-rules.json and schema/semantic-types.json. Do not edit.
// Data display contract: the rule grid and every semantic type's display shape, for resolveValue() in values.js.
export const rules = ${JSON.stringify(contract)};
export const semanticTypes = ${JSON.stringify(semantic)};
`;
// —— agent/components/values.md: the generated sections ——
const contexts = Object.keys(contract.contexts);
const cellOf = (row, c) => {
  const v = row[c];
  if (v == null) return "·";
  const max = row.max?.[c];
  return `\`${v}\`${max ? ` +N after ${max}` : ""}${row.align?.[c] === "end" ? ", right" : ""}`;
};
const sections = {
  rules: contract.rules.map((r, i) => `${i + 1}. ${r}`).join("\n"),
  grid: [
    `| Row | ${contexts.join(" | ")} | Group |`,
    `|---|${contexts.map(() => "---").join("|")}|---|`,
    ...contract.grid.map((r) => `| ${r.label}${r.note ? ` (${r.note.replace(/\.$/, "")})` : ""} | ${contexts.map((c) => cellOf(r, c)).join(" | ")} | ${contract.variants[r.shape].group} |`),
    "",
    "`·` = not shown in that context. Variants and the parts each is built from:",
    "",
    "| Group | Shape | Variants (parts) |",
    "|---|---|---|",
    ...Object.entries(contract.variants).map(([shape, f]) => `| ${f.group} ${f.name} | ${shape} | ${Object.entries(f.variants).map(([k, v]) => `\`${k}\`${v.editable ? " (edit)" : ""}${v.parts.length ? ` ${v.parts.join(", ")}` : ""}`).join(" · ")} |`),
  ].join("\n"),
  aliases: [
    "| Datatable type | Semantic type | Shape | Note |",
    "|---|---|---|---|",
    ...Object.entries(contract.aliases).map(([k, a]) => `| \`${k}\` | ${a.semanticType ? `\`${a.semanticType}\`` : "·"} | ${a.shape ?? semantic[a.semanticType].shape}${a.multiple ? ", several" : ""} | ${a.note ?? (a.display ? `keeps ${Object.entries(a.display).map(([c, v]) => `${v} in ${c}`).join(", ")}` : "")} |`),
  ].join("\n"),
  types: [
    "| Shape | Kind | Semantic types |",
    "|---|---|---|",
    ...Object.keys(contract.shapes).flatMap((shape) => {
      const kinds = [...new Set(types.filter((t) => t.display.shape === shape).map((t) => t.display.kind ?? ""))].sort();
      return kinds.map((k) => `| ${shape} | ${k || "·"} | ${types.filter((t) => t.display.shape === shape && (t.display.kind ?? "") === k).map((t) => `\`${t.key}\`${t.display.unit ? ` (${t.display.unit})` : ""}`).join(", ")} |`);
    }),
  ].join("\n"),
};
const docPath = join(root, "agent/components/values.md");
let doc = readFileSync(docPath, "utf8");
for (const [name, text] of Object.entries(sections)) {
  const re = new RegExp(`(<!-- ${name}:start -->)[\\s\\S]*?(<!-- ${name}:end -->)`);
  if (!re.test(doc)) throw new Error(`agent/components/values.md has no ${name} markers`);
  doc = doc.replace(re, `$1\n${text}\n$2`);
}

const out = join(root, "src/js/value-rules.js");
if (process.argv.includes("--check")) {
  const stale = [];
  if (!existsSync(out) || readFileSync(out, "utf8") !== body) stale.push("src/js/value-rules.js");
  if (readFileSync(docPath, "utf8") !== doc) stale.push("agent/components/values.md");
  if (stale.length) {
    console.error(`${stale.join(" and ")} not current: run node scripts/value-rules.mjs`);
    process.exit(1);
  }
  console.log(`value-rules ok (${contract.grid.length} rows, ${types.length} semantic types, agent doc current)`);
} else {
  writeFileSync(out, body);
  writeFileSync(docPath, doc);
  console.log(`wrote src/js/value-rules.js and agent/components/values.md (${contract.grid.length} rows, ${types.length} semantic types)`);
}
