// Writes src/js/value-rules.js from schema/display-rules.json, schema/semantic-types.json and schema/option-sets.json, so resolveValue()
// (src/js/values.js) reads the same contract in the browser and in Node without a JSON import, and fills the
// generated sections of agent/components/values.md (rules, grid, aliases, types) so the doc cannot drift.
//   node scripts/value-rules.mjs          write
//   node scripts/value-rules.mjs --check  exit 1 when the file is not current (npm test)
// Data display contract W1 and W2b (platform relay/2026-11-14-data-display-contract-plan.md).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const rules = JSON.parse(readFileSync(join(root, "schema/display-rules.json"), "utf8"));
const types = JSON.parse(readFileSync(join(root, "schema/semantic-types.json"), "utf8")).types;
// Option sets (devops.option_sets, migration 435), keyed by set key, published by the platform's publish-firehorse-codex.mts.
const sets = JSON.parse(readFileSync(join(root, "schema/option-sets.json"), "utf8")).sets;
const { $comment, ...contract } = rules;
const optionSets = {};
for (const { key, ...set } of sets) optionSets[key] = set;
const semantic = {};
for (const t of types) {
  // No type may be left without a shape, and every shape is one the grid knows.
  if (!t.display?.shape) throw new Error(`semantic type ${t.key} has no display shape (migrations 434, 435)`);
  if (!contract.shapes[t.display.shape]) throw new Error(`semantic type ${t.key} has shape "${t.display.shape}", which display-rules.json does not know`);
  if (t.display.optionSet && !optionSets[t.display.optionSet]) throw new Error(`semantic type ${t.key} points at option set "${t.display.optionSet}", which schema/option-sets.json does not have`);
  if ((t.display.shape === "option" || t.display.shape === "options") && !t.display.optionSet) throw new Error(`semantic type ${t.key} is an ${t.display.shape} with no option set`);
  semantic[t.key] = {
    label: t.label, shape: t.display.shape, kind: t.display.kind ?? null, unit: t.display.unit ?? null,
    optionSet: t.display.optionSet ?? null, currencyFrom: t.display.currencyFrom ?? null,
    options: Array.isArray(t.options?.options) ? t.options.options : null,
  };
}
const body = `// Generated by scripts/value-rules.mjs from schema/display-rules.json and schema/semantic-types.json. Do not edit.
// Data display contract: the rule grid and every semantic type's display shape, for resolveValue() in values.js.
export const rules = ${JSON.stringify(contract)};
export const semanticTypes = ${JSON.stringify(semantic)};
export const optionSets = ${JSON.stringify(optionSets)};
`;
// —— agent/components/values.md: the generated sections ——
const contexts = Object.keys(contract.contexts);
const cellOf = (row, c) => {
  const v = row[c];
  if (v == null) return "·";
  const max = row.max?.[c];
  return `\`${v}\`${max ? ` +N after ${max}` : ""}${row.align?.[c] === "end" ? ", right" : ""}`;
};
const tonesOf = (set) => set.options.map((o) => `\`${o.value}\`${o.state ? ` ${o.state}` : ""}${o.tone && !o.state ? ` ${o.tone}` : ""}`).join(", ");
const sections = {
  rules: contract.rules.map((r, i) => `${i + 1}. ${r}`).join("\n"),
  grid: [
    `| Row | ${contexts.join(" | ")} | Group |`,
    `|---|${contexts.map(() => "---").join("|")}|---|`,
    ...contract.grid.map((r) => `| ${r.label}${r.note ? ` (${r.note.replace(/\.$/, "")})` : ""} | ${contexts.map((c) => cellOf(r, c)).join(" | ")} | ${contract.variants[r.shape].group} |`),
    "",
    "`·` = not shown in that context. Variants and the parts each is built from:",
    "",
    "| Group | Shape | Variants (parts) |",
    "|---|---|---|",
    ...Object.entries(contract.variants).map(([shape, f]) => `| ${f.group} ${f.name} | ${shape} | ${Object.entries(f.variants).map(([k, v]) => `\`${k}\`${v.editable ? " (edit)" : ""}${v.parts.length ? ` ${v.parts.join(", ")}` : ""}`).join(" · ")} |`),
  ].join("\n"),
  aliases: [
    "| Datatable type | Semantic type | Shape | Note |",
    "|---|---|---|---|",
    ...Object.entries(contract.aliases).map(([k, a]) => `| \`${k}\` | ${a.semanticType ? `\`${a.semanticType}\`` : "·"} | ${a.shape ?? semantic[a.semanticType].shape}${a.multiple ? ", several" : ""} | ${a.note ?? (a.display ? `keeps ${Object.entries(a.display).map(([c, v]) => `${v} in ${c}`).join(", ")}` : "")} |`),
  ].join("\n"),
  "option-sets": [
    "| Set | Kind | Used by | Options (state or tone) |",
    "|---|---|---|---|",
    ...Object.entries(optionSets).map(([key, set]) => `| \`${key}\` ${set.label} | ${set.kind}${set.ordinal ? ", ordinal" : ""}${set.generator ? `, generated (${set.generator}; samples)` : ""} | ${types.filter((t) => t.display.optionSet === key).map((t) => `\`${t.key}\``).join(", ")} | ${tonesOf(set)}${set.ordinal && set.kind !== "status" ? " · ramp in this order" : ""} |`),
  ].join("\n"),
  types: [
    "| Shape | Kind | Semantic types |",
    "|---|---|---|",
    ...Object.keys(contract.shapes).flatMap((shape) => {
      const kinds = [...new Set(types.filter((t) => t.display.shape === shape).map((t) => t.display.kind ?? ""))].sort();
      return kinds.map((k) => `| ${shape} | ${k || "·"} | ${types.filter((t) => t.display.shape === shape && (t.display.kind ?? "") === k).map((t) => `\`${t.key}\`${t.display.unit ? ` (${t.display.unit})` : ""}`).join(", ")} |`);
    }),
  ].join("\n"),
};
// Parts: the VAL family from the full Index (dist/full/index.json, written by the build): each variant's ID, its
// name, the parts it is built from and its markup (read, edit, --lg). Absent before the first build: left as is.
const indexPath = join(root, "dist/full/index.json");
const val = existsSync(indexPath) ? JSON.parse(readFileSync(indexPath, "utf8")).families.find((f) => f.id === "VAL") : null;
if (val) {
  const byId = new Map(val.variants.map((v) => [v.id, v]));
  sections.parts = Object.entries(contract.variants).reduce((acc, [shape, f]) => {
    if (!acc.groups.has(f.group)) { acc.groups.add(f.group); acc.out.push(`#### ${f.group} ${f.name}`, ""); }
    for (const [key, v] of Object.entries(f.variants)) {
      const markup = byId.get(v.id)?.markup;
      if (!markup) throw new Error(`${v.id} (${shape} ${key}) is in display-rules.json but not in the Index`);
      acc.out.push(`\`${v.id}\` ${v.label} · \`${shape}\` \`${key}\`${v.editable ? " · editable" : ""}${v.parts.length ? ` · built from ${v.parts.join(", ")}` : ""}`, "", "```html", markup, "```", "");
    }
    return acc;
  }, { groups: new Set(), out: [] }).out.join("\n").trim();
}
const docPath = join(root, "agent/components/values.md");
let doc = readFileSync(docPath, "utf8");
for (const [name, text] of Object.entries(sections)) {
  const re = new RegExp(`(<!-- ${name}:start -->)[\\s\\S]*?(<!-- ${name}:end -->)`);
  if (!re.test(doc)) throw new Error(`agent/components/values.md has no ${name} markers`);
  // A replacer function, so a $ in the text (a $1.2M sample) is never read as a capture group.
  doc = doc.replace(re, (_, start, end) => `${start}\n${text}\n${end}`);
}

const out = join(root, "src/js/value-rules.js");
if (process.argv.includes("--check")) {
  const stale = [];
  if (!existsSync(out) || readFileSync(out, "utf8") !== body) stale.push("src/js/value-rules.js");
  if (readFileSync(docPath, "utf8") !== doc) stale.push("agent/components/values.md");
  if (stale.length) {
    console.error(`${stale.join(" and ")} not current: run node scripts/value-rules.mjs`);
    process.exit(1);
  }
  console.log(`value-rules ok (${contract.grid.length} rows, ${types.length} semantic types, agent doc current)`);
} else {
  writeFileSync(out, body);
  writeFileSync(docPath, doc);
  console.log(`wrote src/js/value-rules.js and agent/components/values.md (${contract.grid.length} rows, ${types.length} semantic types)`);
}
